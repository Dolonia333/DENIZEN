function normalizeSectionId(raw) {
  const s = String(raw || '').trim().toLowerCase().replace(/_/g, ' ').replace(/-/g, ' ');
  if (!s) return null;
  const compact = s.replace(/\s+/g, '');
  const hit = SECTIONS.find((sec) => sec.id === s || sec.id === compact
    || sec.label.toLowerCase() === s
    || sec.label.toLowerCase().replace(/\s+/g, '') === compact);
  if (hit) return hit.id;
  if (ALIASES[s]) return ALIASES[s];
  if (ALIASES[compact]) return ALIASES[compact];
  return null;
}

function getSectionMeta(idOrLabel) {
  const id = normalizeSectionId(idOrLabel) || String(idOrLabel || '').trim().toLowerCase();
  return SECTIONS.find((s) => s.id === id) || null;
}

function catalogForAgent({ includePhase2 = true } = {}) {
  const sections = SECTIONS
    .filter((s) => includePhase2 || !s.phase2)
    .map((s) => ({
      id: s.id,
      label: s.label,
      group: s.group,
      phase2: !!s.phase2,
      what: s.what,
      used_for: s.used_for,
      capability: s.capability,
      read_tools: s.read_tools,
      write_tools: s.write_tools,
      link_url: s.link_url || null,
      note: s.note || null,
    }));
  return {
    ok: true,
    surface: 'business_studio',
    ui_url: '/business-studio/',
    how_to_help:
      '1) Call business_studio_catalog or business_studio_section with the app name the founder is in. '
      + '2) Use that section’s read_tools before advising. '
      + '3) Mutate only via write_tools — never invent evidence, TAM, or checklist ticks. '
      + '4) Each account has its own studio. The team connector stays on Angela’s studio and cannot open another account. '
      + '5) Phase 2 sections save through business_studio_upsert_section. Do not invent figures.',
    sections,
    start_tools: [
      'business_studio_catalog',
      'business_studio_section',
      'business_studio_working_set',
      'business_studio_brief',
    ],
  };
}

