#!/usr/bin/env python3
"""City structure compiler — GENERATES the base urban layer from a declarative
grid spec, so structure comes from code (not agent guesswork). Emits
data/city-specs/d00-structure.json: continuous paved sidewalk under the urban
core + a connecting asphalt road grid forming real blocks.

Renders first (low depth) so district stamps sit ON the paved city floor
instead of floating on grass. Grass stays the world default outside the
paved cores (parks, rural edges).

Edit CORE_SLABS / ROADS below and re-run; then merge-city-plan.py.
"""

import json
import os

DEN = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(DEN, "data", "city-specs", "d00-structure.json")

# Paved sidewalk slabs covering each urban district's footprint. depth 0.87:
# above the world grass (0), below district patches (~0.9) and stamps.
CORE_SLABS = [
    # (x, y, w, h)
    (180, 1720, 6180, 560),    # CONTINUOUS avenue spine — paves the whole
    #                            main east-west corridor linking every core
    (1760, 380, 960, 1400),    # downtown block (extends down to the spine)
    (3820, 720, 2500, 1560),   # shopping + mainstreet + station NE mass
    (3060, 1660, 1240, 1480),  # civic campus
    (180, 1840, 1520, 1320),   # food-market / west-center
    (560, 1920, 1760, 940),    # plaza apron (overlaps legacy plaza, harmless)
    (2560, 1200, 900, 1080),   # central connector (park-top to avenue)
]

# Asphalt road grid (x, y, w, h). Sidewalk auto-drawn 16px around each by the
# renderer. The avenue (y1880) + verticals already exist in-engine; these ADD
# the cross-streets that bound the core into blocks.
ROADS = [
    (400, 1876, 5900, 64),     # main avenue, extended full width
    (1808, 380, 64, 1560),     # downtown west vertical
    (2560, 380, 64, 3200),     # central vertical artery (existing-ish)
    (3900, 720, 64, 1160),     # civic|shopping divider vertical
    (5240, 760, 64, 1120),     # mainstreet|station divider vertical
    (3820, 1140, 2500, 64),    # NE cross-street (shopping south edge)
    (1760, 1150, 900, 64),     # downtown south cross-street
]


def main():
    frag = {
        "_doc": "GENERATED by compile-city-structure.py — do not hand-edit; "
                "edit the script's CORE_SLABS / ROADS and re-run.",
        "patches": [
            {"tile": "sidewalk", "x": x, "y": y, "w": w, "h": h, "depth": 0.87}
            for (x, y, w, h) in CORE_SLABS
        ],
        "roads": [
            {"x": x, "y": y, "w": w, "h": h} for (x, y, w, h) in ROADS
        ],
        "stamps": [], "anims": [], "animBands": [],
        "solids": [], "labels": [], "portals": [], "npcs": [], "vehicles": [],
    }
    json.dump(frag, open(OUT, "w", encoding="utf-8"), indent=1)
    print(f"wrote {OUT}: {len(CORE_SLABS)} paved slabs, {len(ROADS)} roads")


if __name__ == "__main__":
    main()
